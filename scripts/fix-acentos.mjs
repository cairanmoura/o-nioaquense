// Aplica substituicoes apenas fora de slugs, ids e URLs
// (heuristica: nao substitui dentro de strings que parecem slugs/ids)
const lines = content.split('\n');
const result = lines.map((line) => {
  // Pula linhas que sao slugs, ids ou URLs
  if (/slug:|id:|cover_image_url:|href:|src:/.test(line)) return line;
  // Aplica dicionario
  let out = line;
  for (const [from, to] of Object.entries(dict)) {
    // Word boundary replacement
    const re = new RegExp('\\b' + from.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\b', 'g');
    out = out.replace(re, to);
  }
  return out;
});

